package net.es.nsi.pce.pf;

import java.util.HashMap;
import java.util.Map;
import net.es.nsi.pce.jaxb.dds.CollectionType;
import net.es.nsi.pce.jaxb.dds.DocumentListType;
import net.es.nsi.pce.jaxb.dds.DocumentType;
import net.es.nsi.pce.jaxb.dds.ObjectFactory;
import net.es.nsi.pce.schema.DdsParser;
import net.es.nsi.pce.topology.model.NsiSdpFactory;
import net.es.nsi.pce.topology.model.NsiTopology;
import net.es.nsi.pce.topology.model.NsiTopologyFactory;
import net.es.nsi.pce.topology.provider.DdsWrapper;

/**
 * Builds an NsiTopology from a DDS collection file the way DdsTopologyProvider does, without
 * starting the server. Fixtures live in src/test/resources/topology and are generated by
 * generate.py there.
 */
public final class TopologyFixture {
    private static final String NSA_TYPE = "vnd.ogf.nsi.nsa.v1+xml";
    private static final String TOPOLOGY_TYPE = "vnd.ogf.nsi.topology.v2+xml";
    private static final ObjectFactory FACTORY = new ObjectFactory();

    private TopologyFixture() {
    }

    public static NsiTopology load(String name) throws Exception {
        CollectionType collection = DdsParser.getInstance().readCollection("src/test/resources/topology/" + name);

        NsiTopologyFactory factory = new NsiTopologyFactory();
        factory.setDefaultServiceType("http://services.ogf.org/nsi/2013/12/descriptions/EVTS.A-GOLE");
        factory.setBaseURL("http://localhost:8400/topology");
        NsiTopology topology = factory.createNsiTopology(
                local(collection, NSA_TYPE), byId(collection, NSA_TYPE),
                local(collection, TOPOLOGY_TYPE), byId(collection, TOPOLOGY_TYPE));

        topology.addAllSdp(NsiSdpFactory.createUnidirectionalSdp(topology.getStpMap()));
        topology.addAllSdp(NsiSdpFactory.createBidirectionalSdps(topology.getStpMap()));
        return topology;
    }

    private static DocumentListType local(CollectionType collection, String type) {
        DocumentListType documents = FACTORY.createDocumentListType();
        collection.getLocal().getDocument().stream()
                .filter(document -> type.equals(document.getType()))
                .forEach(documents.getDocument()::add);
        return documents;
    }

    private static Map<String, DdsWrapper> byId(CollectionType collection, String type) {
        Map<String, DdsWrapper> documents = new HashMap<>();
        for (DocumentType document : collection.getDocuments().getDocument()) {
            if (type.equals(document.getType())) {
                DdsWrapper wrapper = new DdsWrapper();
                wrapper.setDocument(document);
                documents.put(document.getId(), wrapper);
            }
        }
        return documents;
    }
}
